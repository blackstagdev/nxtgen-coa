/**
 * Generates docs/product-template-mapping.md from the COA definitions so the
 * documentation always matches the code. Run: npx tsx scripts/gen-mapping-doc.ts
 */
import fs from 'node:fs';
import path from 'node:path';
import { APP_ROOT } from '../src/config.js';
import { allFields, DEFINITIONS } from '../src/coa/definitions/index.js';
import type { CoaDefinition, LayoutOp } from '../src/coa/types.js';

const SHARED = new Set([
  'client', 'client_name', 'client_email', 'sample_name', 'lot_number', 'report_date',
  'received_date', 'articles_tested', 'test_start_date', 'test_end_date',
]);

function placements(def: CoaDefinition): Map<string, string[]> {
  const m = new Map<string, string[]>();
  const add = (k: string, s: string) => m.set(k, [...(m.get(k) ?? []), s]);
  def.pages.forEach((p, i) => {
    const walk = (ops: LayoutOp[], cond = '') => {
      for (const op of ops) {
        const pg = `p${i + 1}`;
        if (op.kind === 'value') add(op.field, `${pg} x${op.x},baseline ${op.y}, max ${op.maxWidth}px${op.maxLines || op.maxHeight ? ', wraps' : ''}${cond}`);
        if (op.kind === 'cell') add(op.field, `${pg} cell x${op.box.x0}-${op.box.x1}, y${op.box.y0}-${op.box.y1}${cond}`);
        if (op.kind === 'image') add(op.field, `${pg} box x${op.box.x0}-${op.box.x1}, y${op.box.y0}-${op.box.y1} (contain)`);
        if (op.kind === 'when') {
          op.uses?.forEach((k) => add(k, `${pg} conditional rendering`));
          walk(op.ops, ' (conditional)');
        }
      }
    };
    walk(p.ops);
  });
  return m;
}

function fieldType(f: ReturnType<typeof allFields>[number]) {
  let t = f.type;
  if (f.type === 'enum') t += ` (${f.options?.join(' / ')})`;
  if (f.type === 'image') t += ` (${f.minImages ?? (f.required ? 1 : 0)}–${f.maxImages ?? 1})`;
  return t + (f.unit ? `, unit “${f.unit}”` : '') + (f.maxLength ? `, ≤${f.maxLength}` : '');
}

const lines: string[] = [];
lines.push('# Product / template mapping');
lines.push('');
lines.push('_Generated from `app/src/coa/definitions/` by `npx tsx scripts/gen-mapping-doc.ts`. Do not edit by hand._');
lines.push('');
lines.push('All blank and completed images are **1414 × 2000 px** (A4 portrait ≈ 171 dpi). Coordinates are pixels on the blank templates (copied to `app/assets/templates/<slug>/blank-pN.png`); completed examples are in `docs/reference/<slug>/filled-pN.png`. Text is Tinos (Times-metric) at 28 px for headers, 23.5 px for the Endotoxin/Sterility grids.');
lines.push('');
lines.push('Signatures, signer blocks, procedures, conclusions, method lines and the footer are **pre-printed** on the blanks and are never generated. No values from the completed examples are used as defaults.');
lines.push('');
lines.push('## Summary');
lines.push('');
lines.push('| Test type (slug) | Status | Pages | Source folder | Blank → Completed example |');
lines.push('|---|---|---|---|---|');
for (const d of DEFINITIONS) {
  const pairs = d.source.blanks.map((b, i) => `\`${b}\` → \`${d.source.filled[i]}\``).join('<br>');
  lines.push(`| ${d.name} (\`${d.slug}\`) | ${d.status} | ${d.pages.length} | \`${d.source.folder}\` | ${pairs} |`);
}
lines.push('');
lines.push('## Shared COA metadata');
lines.push('');
lines.push('Fields used by more than one test type: client / client name, client email (pH, sterility), sample name, lot #, report date, test-article received, number of articles tested, test start/end dates. The **verification key** (`NGA-XXXX-XXXX-XXXX`) is generated by the app and printed in every template\'s “Verification Key” box (large box on HPLC/MS and visual page 2; small box on Endotoxin, pH and ATP page 2).');
lines.push('');
for (const d of DEFINITIONS) {
  const where = placements(d);
  lines.push(`## ${d.name}`);
  lines.push('');
  lines.push(`- Slug: \`${d.slug}\` · definition v${d.version} · status **${d.status}**${d.incompleteReason ? ` — ${d.incompleteReason}` : ''}`);
  lines.push(`- Source: \`${d.source.folder}\` — blanks ${d.source.blanks.map((b) => `\`${b}\``).join(', ')}; completed ${d.source.filled.map((b) => `\`${b}\``).join(', ')}`);
  if (d.reportNumberField) lines.push(`- \`${d.reportNumberField}\` is also stored as the unique report number (duplicates rejected).`);
  lines.push('');
  lines.push('| Field | Key | Scope | Type / validation | Req. | Placement |');
  lines.push('|---|---|---|---|---|---|');
  for (const f of allFields(d)) {
    lines.push(`| ${f.label} | \`${f.key}\` | ${SHARED.has(f.key) ? 'shared' : 'test-specific'} | ${fieldType(f)} | ${f.required ? 'yes' : ''} | ${(where.get(f.key) ?? ['not printed (confirmation only)']).join('<br>')} |`);
  }
  lines.push('');
  lines.push('**Notes, ambiguities and template defects**');
  lines.push('');
  for (const n of d.notes) lines.push(`- ${n}`);
  lines.push('');
}
const out = path.resolve(APP_ROOT, '..', 'docs', 'product-template-mapping.md');
fs.writeFileSync(out, lines.join('\n'));
console.log('wrote', out);
